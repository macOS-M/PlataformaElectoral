import { expect, test } from "@playwright/test";
import { build } from "esbuild";
import { readFile, readdir } from "node:fs/promises";
import { resolve } from "node:path";
let script: string, styles: string;
test.beforeAll(async () => {
  const result = await build({ entryPoints: [resolve("tests/fixtures/territories-ui.tsx")], bundle: true, write: false, format: "iife", platform: "browser", jsx: "automatic" });
  script = result.outputFiles[0].text;
  const files = await readdir(".next/static/chunks");
  styles = (await Promise.all(files.filter(f => f.endsWith(".css")).map(f => readFile(resolve(".next/static/chunks", f), "utf8")))).join("\n").replaceAll("../media/", "/_next/static/media/");
});
test("filtra dependencias, limpia selecciones y conserva catálogos vacíos", async ({ page }, info) => {
  await page.route("**/__territories-ui-test", route => route.fulfill({ contentType: "text/html; charset=utf-8", body: '<!doctype html><html lang="es"><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><main id="root" class="mx-auto max-w-4xl p-4"></main></body></html>' }));
  await page.goto("/__territories-ui-test");
  await page.addStyleTag({ content: styles });
  await page.addScriptTag({ content: script });
  const province = page.getByLabel("Provincia", { exact: true });
  const canton = page.getByLabel("Cantón", { exact: true });
  const district = page.getByLabel("Distrito", { exact: true });
  const submit = page.getByRole("button", { name: "Ver servicios disponibles" });
  await expect(canton).toBeDisabled();
  await province.selectOption({ label: "Provincia A de prueba" });
  await expect(canton.locator("option")).toHaveText(["Seleccioná tu cantón", "Cantón A de prueba", "Cantón vacío de prueba"]);
  await canton.selectOption({ label: "Cantón A de prueba" });
  await expect(district.locator("option")).toHaveText(["Seleccioná tu distrito", "Distrito A de prueba"]);
  await district.selectOption({ label: "Distrito A de prueba" });
  await expect(submit).toBeEnabled();
  await page.screenshot({ path: info.outputPath("jerarquia-territorial.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await province.selectOption({ label: "Provincia B de prueba" });
  await expect(canton).toHaveValue("");
  await expect(district).toHaveValue("");
  await expect(submit).toBeDisabled();
  await canton.selectOption({ label: "Cantón B de prueba" });
  await expect(district.locator("option")).toHaveText(["Seleccioná tu distrito", "Distrito B de prueba"]);
  await province.selectOption({ label: "Provincia A de prueba" });
  await canton.selectOption({ label: "Cantón vacío de prueba" });
  await expect(district).toBeDisabled();
  await expect(district.locator("option")).toHaveCount(1);
  await expect(page.getByRole("status")).toContainText("no tiene distritos activos");
  await expect(province.locator("option")).toHaveText(["Seleccioná tu provincia", "Provincia A de prueba", "Provincia B de prueba"]);
  await province.selectOption("");
  await expect(canton).toBeDisabled();
  await expect(canton.locator("option")).toHaveText(["Seleccioná tu cantón"]);
  await expect(page.locator('input[name="province"]')).toHaveCount(0);
});
