import { expect, test } from "@playwright/test";
import { build } from "esbuild";
import { readFile, readdir } from "node:fs/promises";
import { resolve } from "node:path";
let script: string, styles: string;
test.beforeAll(async () => {
  const bundle = await build({ entryPoints: [resolve("tests/fixtures/training-ui.tsx")], bundle: true, write: false, format: "iife", platform: "browser", jsx: "automatic", plugins: [{ name: "training-action-double", setup(builder) {
    builder.onResolve({ filter: /^next\/link$/ }, () => ({ path: "link", namespace: "training-test" }));
    builder.onLoad({ filter: /^link$/, namespace: "training-test" }, () => ({ contents: 'import {createElement} from "react";export default function Link(props){return createElement("a",props)}', loader: "js", resolveDir: process.cwd() }));
    builder.onLoad({ filter: /[\\/]training[\\/]actions\.ts$/ }, () => ({ contents: 'export async function saveRequirementAction(_state,form){return window.__trainingSave("requirement",form)};export async function saveProgressAction(_state,form){return window.__trainingSave("progress",form)}', loader: "js" }));
  } }] });
  script = bundle.outputFiles[0].text;
  const files = await readdir(".next/static/chunks");
  styles = (await Promise.all(files.filter(f => f.endsWith(".css")).map(f => readFile(resolve(".next/static/chunks", f), "utf8")))).join("\n").replaceAll("../media/", "/_next/static/media/");
});
async function open(page: import("@playwright/test").Page, query = "") {
  await page.route("**/__training-ui-test*", route => route.fulfill({ contentType: "text/html; charset=utf-8", body: '<!doctype html><html lang="es"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><main id="root" class="mx-auto max-w-6xl space-y-6 p-4 sm:p-8"></main></body></html>' }));
  await page.goto(`/__training-ui-test${query}`);
  await page.addStyleTag({ content: styles });
  await page.addScriptTag({ content: script });
  await expect(page.getByRole("heading", { name: "Plan de capacitación" })).toBeVisible();
}
test("busca, filtra pendientes y mantiene el historial fuera del flujo principal", async ({ page }, info) => {
  await open(page);
  await expect(page.getByRole("article")).toHaveCount(9);
  await expect(page.getByRole("progressbar")).toHaveAttribute("aria-valuenow", "17");
  await page.screenshot({ path: info.outputPath("capacitacion.png"), fullPage: true });
  await page.getByLabel("Buscar puesto o persona").fill("coordinacion general");
  await expect(page.getByRole("article")).toHaveCount(1);
  await expect(page.getByRole("article")).toContainText("Coordinación General Cantonal");
  await page.getByLabel("Buscar puesto o persona").fill("");
  await page.getByRole("button", { name: /^En seguimiento/ }).click();
  await expect(page.getByRole("article")).toHaveCount(5);
  await expect(page.getByRole("article", { name: "Coordinación distrital", exact: true })).toHaveCount(0);
  await page.getByLabel("Buscar puesto o persona").fill("sin coincidencias");
  await expect(page.getByRole("heading", { name: "No encontramos coincidencias" })).toBeVisible();
  await page.getByRole("button", { name: "Limpiar filtros" }).click();
  await expect(page.getByRole("article")).toHaveCount(9);
  await page.locator("summary").filter({ hasText: "Historial de requisitos y estados" }).click();
  await expect(page.getByText("Revisión 1", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test("configura con una decisión explícita y conserva datos después de un rechazo", async ({ page }, info) => {
  await open(page);
  await page.getByRole("article", { name: "Coordinación General Cantonal", exact: true }).getByRole("button", { name: "Configurar puesto" }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("button", { name: "Guardar requisito" })).toBeDisabled();
  await dialog.getByRole("radio", { name: /^Requiere capacitación/ }).check();
  await dialog.getByLabel("Fecha de capacitación", { exact: false }).fill("2026-12-01");
  await page.evaluate(() => { window.__trainingRejectNext = true; });
  await dialog.getByRole("button", { name: "Guardar requisito" }).click();
  await expect(dialog.getByRole("alert")).toContainText("Los datos se conservan");
  await expect(dialog.getByRole("radio", { name: /^Requiere capacitación/ })).toBeChecked();
  await expect(dialog.getByLabel("Fecha de capacitación", { exact: false })).toHaveValue("2026-12-01");
  await page.screenshot({ path: info.outputPath("capacitacion-requisito.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Guardar requisito" }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: "Requisito guardado" })).toBeVisible();
  const submitted = await page.evaluate(() => window.__trainingSubmissions.at(-1));
  expect(submitted?.data.required).toBe("on");
  expect(submitted?.data.scheduledOn).toBe("2026-12-01");
});
test("distingue configuración de avance y previene fechas y estados incompatibles", async ({ page }, info) => {
  await open(page);
  await page.getByRole("article", { name: "Signos externos", exact: true }).getByRole("button", { name: "Configurar Signos externos", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("radio", { name: /^No requerida/ }).check();
  await expect(dialog.getByText("Este cambio inicia una nueva revisión.", { exact: false })).toBeVisible();
  await dialog.getByRole("button", { name: "Cerrar ventana" }).click();
  await page.getByRole("article", { name: "Alimentación", exact: true }).getByRole("button", { name: "Registrar avance" }).click();
  await expect(dialog.getByRole("radio", { name: /^Convocado/ })).toBeDisabled();
  await expect(dialog.getByRole("radio", { name: /^Cumplido/ })).toBeDisabled();
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  await page.getByRole("article", { name: "Coordinación Día E", exact: true }).getByRole("button", { name: "Registrar avance" }).click();
  await expect(dialog.getByRole("radio", { name: /^Convocado/ })).toBeEnabled();
  await expect(dialog.getByRole("radio", { name: /^No asistió/ })).toBeDisabled();
  await dialog.getByRole("button", { name: "Cerrar ventana" }).click();
  await page.getByRole("article", { name: "Electorales", exact: true }).getByRole("button", { name: "Registrar avance" }).click();
  await dialog.getByRole("radio", { name: /^Cumplido/ }).check();
  const date = dialog.getByLabel("Fecha del registro", { exact: true });
  await expect(date).toHaveAttribute("min", "2020-01-10");
  await expect(date).toHaveAttribute("max", "2026-11-07");
  await date.fill("2020-01-10");
  await page.screenshot({ path: info.outputPath("capacitacion-avance.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Registrar estado" }).click();
  await expect(dialog).not.toBeVisible();
  expect((await page.evaluate(() => window.__trainingSubmissions.at(-1)))?.data.status).toBe("cumplido");
});
test("ofrece una vista de consulta y un estado vacío sin mutaciones", async ({ page }) => {
  await open(page, "?reader=1");
  await expect(page.getByRole("button", { name: "Registrar avance" })).toHaveCount(0);
  await page.getByRole("article", { name: "Transporte", exact: true }).getByRole("button", { name: "Ver detalle" }).click();
  await expect(page.getByRole("dialog").getByText("Capacitación requerida", { exact: true })).toBeVisible();
  await expect(page.getByRole("dialog").getByRole("button", { name: "Guardar requisito" })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await open(page, "?empty=1");
  await expect(page.getByRole("heading", { name: "No hay puestos disponibles." })).toBeVisible();
  await expect(page.getByRole("link", { name: "Ver organigrama" })).toBeVisible();
  await expect(page.getByRole("button", { name: /^Puestos/ })).toHaveCount(0);
});
